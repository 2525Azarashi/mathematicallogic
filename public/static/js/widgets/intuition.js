//  4. さわって10秒で腑に落ちる「直感→本質 マイクロ図解ラボ（3連）」
// ============================================================
export function microIntuitionLabs() {
  // Mini Lab A: ∀x∃y vs ∃y∀x 2×2 マトリクス直感チェッカー
  const gridState = [[false, true], [true, false]] // 初期値：対角が⊥、反対角が⊤（∀x∃y=⊤, ∃y∀x=⊥ の黄金反例！）
  const cellBox = h('div.ie-mini-body')

  function drawQuantGrid() {
    cellBox.innerHTML = ''
    const allEx = [0, 1].every((x) => [0, 1].some((y) => gridState[x][y]))
    const exAll = [0, 1].some((y) => [0, 1].every((x) => gridState[x][y]))

    const tbl = h('table.ie-qmat',
      h('tr', h('th', 'R(x, y)'), h('th', 'y = 1'), h('th', 'y = 2'), h('th.ie-qcol', '各行に⊤ある？')),
      ...[0, 1].map((x) => {
        const rowOk = gridState[x][0] || gridState[x][1]
        return h('tr',
          h('th', `x = ${x + 1}`),
          ...[0, 1].map((y) => h('td', h('button.mc-cell', {
            type: 'button',
            class: gridState[x][y] ? 't' : 'f',
            html: gridState[x][y] ? '⊤' : '⊥',
            onclick: () => { gridState[x][y] = !gridState[x][y]; drawQuantGrid() },
          }))),
          h('td.ie-qchk', { html: rowOk ? '<b class="c-top">✓ あり</b>' : '<b class="c-bot">✕ なし</b>' }))
      }),
      h('tr.ie-qfoot',
        h('th', '列ぜんぶ⊤？'),
        ...[0, 1].map((y) => {
          const colOk = gridState[0][y] && gridState[1][y]
          return h('td', { html: colOk ? '<b class="c-top">✓ 全部⊤</b>' : '<b class="c-bot">✕</b>' })
        }),
        h('td', '')))

    cellBox.append(
      tbl,
      h('div.ie-mini-verdicts',
        h('div.ie-mv', { class: allEx ? 'ok' : 'ng' },
          h('span.fx', { html: fxs('∀x∃y R(x,y)') }),
          h('small', '＝「どの行にも最低1つ⊤がある」'),
          h('span', { html: tv(allEx) })),
        h('div.ie-mv', { class: exAll ? 'ok' : 'ng' },
          h('span.fx', { html: fxs('∃y∀x R(x,y)') }),
          h('small', '＝「縦1列まるごと⊤の列がある」'),
          h('span', { html: tv(exAll) }))))
  }
  drawQuantGrid()

  // Mini Lab B: Skolem化「前に ∀ があるかないか」1タップ比較
  let skHasAll = true
  const skBody = h('div.ie-mini-body')
  function drawSkolemMini() {
    skBody.innerHTML = ''
    skBody.append(
      h('div.ie-sk-toggle',
        h('button.mt-fbtn', { type: 'button', class: !skHasAll ? 'on' : '', onclick: () => { skHasAll = false; drawSkolemMini() } }, '前に ∀ がない：∃y R(a, y)'),
        h('button.mt-fbtn', { type: 'button', class: skHasAll ? 'on' : '', onclick: () => { skHasAll = true; drawSkolemMini() } }, '前に ∀x がある：∀x∃y R(x, y)')),
      skHasAll
        ? html(`<div class="ie-sk-vis">
            <div class="ie-sk-map"><span>x = 1 ──▶ 相手 <b>f(1)</b></span><span>x = 2 ──▶ 相手 <b>f(2)</b></span></div>
            <p><b>直感：</b>$y$ は $x$ ごとに別人でよい（後出しOK）！ だから1つの定数 $c$ に決め打ちせず、<b>「$x$ を入れたらその相手を返す関数 $f(x)$」</b>で置き換えて <span class="fx">∀x R(x, f(x))</span> にする。</p>
          </div>`)
        : html(`<div class="ie-sk-vis">
            <div class="ie-sk-map"><span>誰にも依存しない1人 ──▶ <b>定数 c</b></span></div>
            <p><b>直感：</b>前に $\\forall$ が1つもないので、条件を満たす誰か1人を連れてきて<b>「その人を定数 $c$ と呼ぶ！」</b>と名前をつけるだけでよく、<span class="fx">R(a, c)</span> になる。</p>
          </div>`))
  }
  drawSkolemMini()

  // Mini Lab C: なぜ「異なる節の x は別人」で「同じ節の x は同一人物」なのか？
  let sameClause = false
  const varBody = h('div.ie-mini-body')
  function drawVarScopeMini() {
    varBody.innerHTML = ''
    varBody.append(
      h('div.ie-sk-toggle',
        h('button.mt-fbtn', { type: 'button', class: !sameClause ? 'on' : '', onclick: () => { sameClause = false; drawVarScopeMini() } }, '別々の2節：{ P(x), ¬P(f(x)) }'),
        h('button.mt-fbtn', { type: 'button', class: sameClause ? 'on' : '', onclick: () => { sameClause = true; drawVarScopeMini() } }, '同じ1節内：{ P(x) ∨ Q(x) }')),
      !sameClause
        ? html(`<div class="ie-sk-vis">
            <div class="ie-sk-map"><span>正体：<span class="fx">(∀x P(x)) ∧ (∀x ¬P(f(x)))</span></span></div>
            <p><b>本質：</b>$\\forall$ は $\\land$ に分配できるので、節ごとの $x$ は<b>別々の $\\forall$ に束縛された「同姓同名の他人」</b>！ だからぶつける前に <span class="fx">¬P(f(x₁))</span> と別名に分けてから mgu $\\{x := f(x_1)\\}$ で単一化できる。</p>
          </div>`)
        : html(`<div class="ie-sk-vis">
            <div class="ie-sk-map"><span>正体：<span class="fx">∀x (P(x) ∨ Q(x))</span>　※ ∀は∨に分配不可！</span></div>
            <p><b>本質：</b>1つの節の $\\lor$ は<b>1つの同じ $\\forall x$ のスコープの中</b>にある「同一人物」！ だから $P(x)$ を $\\{x := a\\}$ で打ち消した瞬間、相棒の $Q(x)$ も連動して強制的に <span class="fx">Q(a)</span> に変わる。</p>
          </div>`))
  }
  drawVarScopeMini()

  return h('div.ie-mini-grid.reveal',
    h('div.ie-mini-card',
      h('span.ig-tag', '10秒で納得 ① · 量化の順序'),
      h('h5', 'なぜ ∀x∃y と ∃y∀x は逆にならない？（マスを押して体験）'),
      cellBox),
    h('div.ie-mini-card',
      h('span.ig-tag', '10秒で納得 ② · Skolem化の本質'),
      h('h5', 'なぜ Skolem 化で「定数 c」と「関数 f(x)」に分かれるの？'),
      skBody),
    h('div.ie-mini-card',
      h('span.ig-tag', '10秒で納得 ③ · 第7〜8回の最重要急所'),
      h('h5', 'なぜ「別節の x は分離」し、「同節の x は連動」するの？'),
      varBody))
}

