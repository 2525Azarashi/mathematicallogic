function comprehensiveExamplesSection(onMasteryChange) {
  let mastered = new Set(store.get('midterm-ex-chk', []))
  const kwChecked = new Set(store.get('midterm-kw-chk', []))
  let lecFilter = 'all' // 'all' | 'star' | 1..8
  let onlyUnchecked = false
  let expandAll = false
  let searchQuery = ''

  const progFill = h('i')
  const progLabel = h('span.mt-ex-stat')
  const listWrap = h('div.mt-ex-list')

  function updateSummary() {
    const pct = Math.round((mastered.size / ALL_EXAMPLES.length) * 100)
    progFill.style.width = pct + '%'
    progLabel.textContent = `例題・演習 説明できる度：${mastered.size} / ${ALL_EXAMPLES.length} 題（${pct}%）`
    if (onMasteryChange) onMasteryChange(mastered.size, ALL_EXAMPLES.length)
  }

  let deckReady = false
  const fcDeck = flashcardDeckWidget(ALL_EXAMPLES, () => {
    if (!deckReady) return
    mastered = new Set(store.get('midterm-ex-chk', []))
    updateSummary()
    renderCards()
  })
  deckReady = true

  const LEC_BTNS = [
    ['all', `全25題`],
    ['star', `★ エッセンシャル厳選 (${ALL_EXAMPLES.filter((e) => e.star).length})`],
    [1, '第1回'],
    [2, '第2回'],
    [3, '第3回'],
    [4, '第4回'],
    [5, '第5回'],
    [6, '第6回'],
    [7, '第7回'],
    [8, '第8回'],
  ]

  const filterBar = h('div.mt-ex-filters')
  const renderFilterBtns = () => {
    filterBar.innerHTML = ''
    LEC_BTNS.forEach(([val, label]) => {
      filterBar.append(h('button.mt-fbtn', {
        type: 'button',
        class: lecFilter === val ? 'on' : '',
        onclick: () => { lecFilter = val; renderFilterBtns(); renderCards() },
      }, label))
    })
  }

  const searchIn = h('input.mt-ex-search', {
    type: 'search',
    placeholder: '🔍 キーワード絞り込み（例：Skolem, 恒真性保持, mgu, 自由変数, 初期シーケント…）',
    'aria-label': '例題キーワード検索',
    oninput: (e) => { searchQuery = e.target.value.trim().toLowerCase(); renderCards() },
  })

  const unchkToggle = h('label.mt-ex-tog',
    h('input', {
      type: 'checkbox',
      onchange: (e) => { onlyUnchecked = e.target.checked; renderCards() },
    }),
    ' 未習得（「説明できる」未チェック）のみ表示')

  const expandBtn = h('button.btn.sm', {
    type: 'button',
    onclick: () => {
      expandAll = !expandAll
      expandBtn.textContent = expandAll ? '▲ 解説をすべて閉じる' : '▼ すべての「なぜそうなるか」を一括展開'
      listWrap.querySelectorAll('details.mt-ex-why').forEach((d) => { d.open = expandAll })
    },
  }, '▼ すべての「なぜそうなるか」を一括展開')

  function renderCards() {
    listWrap.innerHTML = ''
    const items = ALL_EXAMPLES.filter((it) => {
      if (lecFilter === 'star' && !it.star) return false
      if (typeof lecFilter === 'number' && it.lec !== lecFilter) return false
      if (onlyUnchecked && mastered.has(it.id)) return false
      if (searchQuery) {
        const meta = EXAMPLE_META[it.id] || { keys: [], trap: '' }
        const hay = `${it.badge} ${it.title} ${it.q} ${it.point} ${it.why} ${meta.keys.join(' ')} ${meta.trap}`.toLowerCase()
        if (!hay.includes(searchQuery)) return false
      }
      return true
    })

    if (!items.length) {
      listWrap.append(h('div.mt-ex-empty', '🎉 条件に一致する未習得の例題はありません！ フィルタや検索語を切り替えて確認しましょう。'))
      return
    }

    items.forEach((it) => {
      const isDone = mastered.has(it.id)
      const meta = EXAMPLE_META[it.id] || { keys: [], trap: '' }

      const setMastered = (val, targetEl) => {
        if (val) {
          mastered.add(it.id)
          if (mastered.size === ALL_EXAMPLES.length && targetEl) {
            confettiAt(targetEl)
            toast({ msg: '全25例題の「なぜそうなるか」制覇！ 高得点ルート完了です！', type: 'qed' })
          }
        } else {
          mastered.delete(it.id)
        }
        store.set('midterm-ex-chk', [...mastered])
        cb.checked = val
        card.classList.toggle('done', val)
        updateSummary()
        if (onlyUnchecked && val) renderCards()
      }

      const cb = h('input', {
        type: 'checkbox',
        checked: isDone,
        onchange: (e) => setMastered(e.target.checked, e.target),
      })

      // Interactive self-grading keyword chips inside answer
      const kwSection = meta.keys.length
        ? h('div.mt-kp-box',
            h('b', '🔑 自己採点チェック（口頭説明や下書きにこのフレーズが入っていればタップ！ 全部揃うと自動で習得 ✓）：'),
            h('div.mt-kp-chips', ...meta.keys.map((k, ki) => {
              const kId = `${it.id}:${ki}`
              const btn = h('button.mt-kp.chk', {
                type: 'button',
                class: kwChecked.has(kId) ? 'on' : '',
                html: rich(k),
                onclick: (e) => {
                  if (kwChecked.has(kId)) kwChecked.delete(kId)
                  else kwChecked.add(kId)
                  store.set('midterm-kw-chk', [...kwChecked])
                  btn.classList.toggle('on', kwChecked.has(kId))
                  const allHit = meta.keys.every((_, j) => kwChecked.has(`${it.id}:${j}`))
                  if (allHit && !mastered.has(it.id)) {
                    setMastered(true, e.currentTarget)
                    toast({ msg: `「${it.badge}」の必須キーワードをすべて確認！ 習得済みにしました ✓`, type: 'ok' })
                  }
                },
              })
              return btn
            })))
        : null

      const treeBox = WANG_INLINE[it.id]
        ? h('div.mt-inline-trees',
            ...WANG_INLINE[it.id].map((seqStr) => h('div.pf-scroll', staticTree(wang(parseSequent(seqStr))))))
        : null

      const trapBox = meta.trap
        ? h('div.mt-trap-line', { html: rich(`<b>⚠️ よくある減点ミス：</b>${meta.trap}`) })
        : null

      const det = h('details.mt-ex-why',
        h('summary', '💡 なぜそうなるか（定義に基づく模範説明・採点キーワード・減点回避）を開く'),
        kwSection,
        h('div.mt-ex-ans.proof-text', { html: rich(it.why) }),
        treeBox,
        trapBox)
      if (expandAll) det.open = true

      const card = h('article.mt-ex-card', { class: isDone ? 'done' : '' },
        h('div.mt-ex-top',
          h('div.mt-ex-badges',
            h('span.mt-eb-lec', `第${it.lec}回`),
            h('span.mt-eb-kind', { class: it.kind }, it.badge),
            it.star ? h('span.mt-eb-star', '★ 高得点必須') : null),
          h('div.mt-ex-acts',
            h('a.chip', { href: it.href }, 'ラボで触る →'),
            h('label.mt-eb-chk', cb, '説明できる ✓'))),
        h('h4.mt-ex-title', { html: rich(it.title) }),
        h('div.mt-ex-q', { html: rich(it.q) }),
        h('div.mt-ex-pt', { html: rich(`<b>着眼点：</b>${it.point}`) }),
        det)

      listWrap.append(card)
    })
  }

  renderFilterBtns()
  updateSummary()
  renderCards()

  return h('div.mt-ex-catalog',
    fcDeck,
    h('div.mt-ex-progbar.reveal',
      progLabel,
      h('div.pbar', progFill)),
    h('div.mt-ex-ctrl.reveal',
      searchIn,
      filterBar,
      h('div.mt-ex-subctrl', unchkToggle, expandBtn)),
    listWrap)
}

